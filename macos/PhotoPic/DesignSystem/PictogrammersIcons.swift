/// Crisp vector SwiftUI view rendering any extracted Pictogrammers icon.
package struct PictogrammersIcon: View {
    let asset: PictogrammersAsset
    let size: CGFloat

    package init(_ asset: PictogrammersAsset, size: CGFloat = 14) {
        self.asset = asset
        self.size = size
    }

    package var body: some View {
        Image(nsImage: asset.templateNSImage(pointSize: size))
            .renderingMode(.template)
            .resizable()
            .interpolation(.high)
            .aspectRatio(contentMode: .fit)
            .frame(width: size, height: size)
    }
}
